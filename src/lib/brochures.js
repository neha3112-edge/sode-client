export function normalizeUniversitySlug(nameOrSlug) {
  if (!nameOrSlug) return "";
  const s = String(nameOrSlug).toLowerCase().trim();

  // 1. Direct match in dictionary
  if (BROCHURES_BY_UNIVERSITY[s]) return s;

  // 2. Synonyms mapping
  for (const [key, slug] of Object.entries(UNIVERSITY_SLUG_SYNONYMS)) {
    if (s === key || s.includes(key)) {
      if (BROCHURES_BY_UNIVERSITY[slug]) return slug;
    }
  }

  // 3. Normalized alphanumeric
  const clean = s.replace(/[^a-z0-9]/g, "");
  for (const slug of Object.keys(BROCHURES_BY_UNIVERSITY)) {
    if (clean.includes(slug)) return slug;
  }

  return s;
}

export function extractCourseCode(course) {
  if (!course) return "";
  const c = String(course).toLowerCase().trim();

  // Check specific multi-word phrases first
  if (
    c.includes("executive mba") ||
    c.includes("executive master of business") ||
    /(^|[^a-z])emba([^a-z]|$)/i.test(c)
  ) {
    return "emba";
  }

  if (
    c.includes("master of business") ||
    c.includes("master in business") ||
    /(^|[^a-z])mba([^a-z]|$)/i.test(c)
  ) {
    return "mba";
  }

  if (
    c.includes("bachelor of business") ||
    c.includes("bachelor in business") ||
    /(^|[^a-z])bba([^a-z]|$)/i.test(c)
  ) {
    return "bba";
  }

  if (
    c.includes("master of computer") ||
    c.includes("master in computer") ||
    /(^|[^a-z])mca([^a-z]|$)/i.test(c)
  ) {
    return "mca";
  }

  if (
    c.includes("bachelor of computer") ||
    c.includes("bachelor in computer") ||
    /(^|[^a-z])bca([^a-z]|$)/i.test(c)
  ) {
    return "bca";
  }

  if (
    c.includes("master of commerce") ||
    c.includes("master in commerce") ||
    /(^|[^a-z])m\.?\s*com([^a-z]|$)/i.test(c)
  ) {
    return "mcom";
  }

  if (
    c.includes("bachelor of commerce") ||
    c.includes("bachelor in commerce") ||
    /(^|[^a-z])b\.?\s*com([^a-z]|$)/i.test(c)
  ) {
    return "bcom";
  }

  if (
    c.includes("master of science") ||
    c.includes("master in science") ||
    /(^|[^a-z])m\.?\s*sc([^a-z]|$)/i.test(c)
  ) {
    return "msc";
  }

  if (
    c.includes("bachelor of science") ||
    c.includes("bachelor in science") ||
    /(^|[^a-z])b\.?\s*sc([^a-z]|$)/i.test(c)
  ) {
    return "bsc";
  }

  if (
    (c.includes("journalism") && c.includes("master")) ||
    /(^|[^a-z])mjmc([^a-z]|$)/i.test(c)
  ) {
    return "mjmc";
  }

  if (c.includes("journalism") || /(^|[^a-z])bjmc([^a-z]|$)/i.test(c)) {
    return "bjmc";
  }

  if (
    c.includes("doctor of business") ||
    /(^|[^a-z])dba([^a-z]|$)/i.test(c)
  ) {
    return "dba";
  }

  if (
    c.includes("master of arts") ||
    c.includes("master in arts") ||
    /(^|[^a-z])m\.?\s*a\.?([^a-z]|$)/i.test(c)
  ) {
    return "ma";
  }

  if (
    c.includes("bachelor of arts") ||
    c.includes("bachelor in arts") ||
    /(^|[^a-z])b\.?\s*a\.?([^a-z]|$)/i.test(c)
  ) {
    return "ba";
  }

  return "";
}

/**
 * Resolves the brochure PDF URL for a university and optional course.
 * @param {string} university - University slug or name
 * @param {string} [course] - Selected course title or code
 * @param {object} [brandFallback] - Fallback brand object
 * @returns {string} Fully encoded URL to the brochure PDF
 */
export function resolveBrochurePdfUrl(university, course, brandFallback = {}) {
  const slug = normalizeUniversitySlug(university || brandFallback?.slug || "");
  const files = BROCHURES_BY_UNIVERSITY[slug] || [];

  if (files.length > 0) {
    const code = extractCourseCode(course);

    if (code) {
      // 1. Try exact course token in filename
      const match = files.find((fn) => {
        const lower = fn.toLowerCase();
        return new RegExp('(^|[_\\-\\s])' + code + '([_\\-\\s\\.]|$)', 'i').test(lower);
      });
      if (match) {
        return encodeURI(`/LP Brochures/LP Brochures/${slug}/${match}`);
      }
    }

    // 2. Try main university brochure
    const mainBrochure = files.find((fn) => {
      const lower = fn.toLowerCase();
      return (
        lower.includes("main") ||
        lower.includes("university") ||
        lower.includes("all_brochure") ||
        lower.includes("all_in_one") ||
        lower.includes("final")
      );
    });
    if (mainBrochure) {
      return encodeURI(`/LP Brochures/LP Brochures/${slug}/${mainBrochure}`);
    }

    // 3. Fallback to first available file in university folder
    return encodeURI(`/LP Brochures/LP Brochures/${slug}/${files[0]}`);
  }

  // Fallback to configured brand brochure or default
  return (
    brandFallback?.brochurePdf ||
    brandFallback?.brochureUrl ||
    "/assets/pdf/brochure.pdf"
  );
}
